# ==========================================
#        Generate Common Variants
# ==========================================
# افزودن شکل‌های رایج با پسوندهای متداول.
# این قسمت تعداد حالت‌های قابل تشخیص را افزایش می‌دهد.

def _make_variants(words):
    variants = set(words)

    suffixes = (
        "ی",
        "یا",
        "ها",
        "های",
        "تر",
        "ترین",
        "م",
        "ت",
        "ش",
        "مون",
        "تون",
        "شون",
    )

    # فقط روی واژه‌های نسبتاً بلند پسوند اضافه می‌کنیم
    # تا تعداد خطاهای تشخیص برای کلمات کوتاه کم بماند.
    for word in tuple(words):
        normalized = word.replace("‌", "").replace(" ", "")

        if len(normalized) < 4:
            continue

        for suffix in suffixes:
            variants.add(normalized + suffix)

    return variants


